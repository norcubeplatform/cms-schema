// Command catalogjson writes report/catalog.json: every rule and cause
// a finding can have, the reasons a quality rule is skipped and the
// codes of a refused fact, each with the Params keys it sets, and the
// keys with their types and classes. Clients that word findings
// themselves (the dashboard, the CMS's Swagger) are generated from it,
// so a new cause is a type error there until it has words.
//
//	go generate ./report
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"

	"github.com/norcubeplatform/cms-schema/fact"
	"github.com/norcubeplatform/cms-schema/quality"
	"github.com/norcubeplatform/cms-schema/report"
)

// Catalog is the file's shape.
type Catalog struct {
	// Comment says where the file comes from.
	Comment     string                   `json:"$comment"`
	Params      []report.ParamSpec       `json:"params"`
	Findings    []report.CauseSpec       `json:"findings"`
	SkipReasons []quality.SkipReasonSpec `json:"skipReasons"`
	FactErrors  []fact.ErrorSpec         `json:"factErrors"`
}

func build() ([]byte, error) {
	c := Catalog{
		Comment:     "Generated by `go generate ./report` from report.Catalog(), quality.SkipReasons() and fact.ErrorCodes(). Do not edit.",
		Params:      report.ParamSpecs(),
		Findings:    report.Catalog(),
		SkipReasons: quality.SkipReasons(),
		FactErrors:  fact.ErrorCodes(),
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(c); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func main() {
	out := flag.String("o", "catalog.json", "file to write")
	flag.Parse()
	b, err := build()
	if err == nil {
		err = os.WriteFile(*out, b, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "catalogjson:", err)
		os.Exit(1)
	}
}
